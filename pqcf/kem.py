"""
Key Encapsulation Mechanisms (KEMs) behind one common interface.

Every algorithm - classical, post-quantum or hybrid - exposes the same three
operations, so application code never depends on a specific algorithm.
That common interface is what makes the framework crypto-agile.

    keygen()            -> (public_key, secret_key)
    encaps(public_key)  -> (ciphertext, shared_secret)   # sender side
    decaps(secret_key, ciphertext) -> shared_secret      # receiver side
"""

import os
import struct
from abc import ABC, abstractmethod

import oqs
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding, rsa, x25519
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

SHARED_SECRET_LEN = 32


def _hkdf(ikm: bytes, info: bytes, length: int = SHARED_SECRET_LEN) -> bytes:
    return HKDF(algorithm=hashes.SHA256(), length=length, salt=None, info=info).derive(ikm)


def _pack(*parts: bytes) -> bytes:
    """Length-prefix each part so concatenations are unambiguous."""
    return b"".join(struct.pack(">I", len(p)) + p for p in parts)


def _unpack(blob: bytes) -> list:
    parts, i = [], 0
    while i < len(blob):
        (n,) = struct.unpack(">I", blob[i:i + 4])
        parts.append(blob[i + 4:i + 4 + n])
        i += 4 + n
    return parts


class KEM(ABC):
    name: str = "abstract"
    family: str = "abstract"        # classical | post-quantum | hybrid
    quantum_safe: bool = False

    @abstractmethod
    def keygen(self) -> tuple: ...

    @abstractmethod
    def encaps(self, public_key: bytes) -> tuple: ...

    @abstractmethod
    def decaps(self, secret_key: bytes, ciphertext: bytes) -> bytes: ...


# --------------------------------------------------------------------------
# Classical KEMs (broken by Shor's algorithm on a large quantum computer)
# --------------------------------------------------------------------------

class X25519KEM(KEM):
    """Elliptic-curve Diffie-Hellman (X25519) used as a KEM (DHKEM-style)."""
    name, family, quantum_safe = "X25519", "classical", False

    def keygen(self):
        sk = x25519.X25519PrivateKey.generate()
        pk = sk.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        skb = sk.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                               serialization.NoEncryption())
        return pk, skb

    def encaps(self, public_key):
        eph = x25519.X25519PrivateKey.generate()
        eph_pub = eph.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        dh = eph.exchange(x25519.X25519PublicKey.from_public_bytes(public_key))
        ss = _hkdf(dh, b"X25519-KEM" + eph_pub + public_key)
        return eph_pub, ss

    def decaps(self, secret_key, ciphertext):
        sk = x25519.X25519PrivateKey.from_private_bytes(secret_key)
        pk = sk.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        dh = sk.exchange(x25519.X25519PublicKey.from_public_bytes(ciphertext))
        return _hkdf(dh, b"X25519-KEM" + ciphertext + pk)


class RSAOAEPKEM(KEM):
    """RSA-OAEP key transport: a random secret is encrypted to the receiver."""
    family, quantum_safe = "classical", False

    def __init__(self, bits: int = 3072):
        self.bits = bits
        self.name = f"RSA-{bits}"
        self._pad = padding.OAEP(mgf=padding.MGF1(hashes.SHA256()), algorithm=hashes.SHA256(), label=None)

    def keygen(self):
        sk = rsa.generate_private_key(public_exponent=65537, key_size=self.bits)
        pk = sk.public_key().public_bytes(serialization.Encoding.DER,
                                          serialization.PublicFormat.SubjectPublicKeyInfo)
        skb = sk.private_bytes(serialization.Encoding.DER, serialization.PrivateFormat.PKCS8,
                               serialization.NoEncryption())
        return pk, skb

    def encaps(self, public_key):
        ss = os.urandom(SHARED_SECRET_LEN)
        ct = serialization.load_der_public_key(public_key).encrypt(ss, self._pad)
        return ct, ss

    def decaps(self, secret_key, ciphertext):
        # key was generated by us, so skip the (expensive) re-validation on load;
        # otherwise the benchmark would measure key parsing instead of RSA itself
        sk = serialization.load_der_private_key(secret_key, password=None,
                                                unsafe_skip_rsa_key_validation=True)
        return sk.decrypt(ciphertext, self._pad)


# --------------------------------------------------------------------------
# Post-quantum KEMs (NIST FIPS 203, via the Open Quantum Safe library)
# --------------------------------------------------------------------------

class OQSKEM(KEM):
    """Any KEM provided by liboqs, e.g. ML-KEM-768 (FIPS 203)."""
    family, quantum_safe = "post-quantum", True

    def __init__(self, alg: str):
        if alg not in oqs.get_enabled_kem_mechanisms():
            raise ValueError(f"{alg} is not enabled in this liboqs build")
        self.name = alg

    def keygen(self):
        with oqs.KeyEncapsulation(self.name) as kem:
            pk = kem.generate_keypair()
            sk = kem.export_secret_key()
        return pk, sk

    def _normalise(self, ss, ct):
        # Some KEMs (e.g. FrodoKEM-976: 24 bytes) don't output 32-byte secrets.
        # Derive a 32-byte key so AES-256 is always used. ML-KEM is left as-is.
        if len(ss) == SHARED_SECRET_LEN:
            return ss
        return _hkdf(ss, b"PQCF-normalise|" + self.name.encode() + ct)

    def encaps(self, public_key):
        with oqs.KeyEncapsulation(self.name) as kem:
            ct, ss = kem.encap_secret(public_key)
        return ct, self._normalise(ss, ct)

    def decaps(self, secret_key, ciphertext):
        with oqs.KeyEncapsulation(self.name, secret_key=secret_key) as kem:
            return self._normalise(kem.decap_secret(ciphertext), ciphertext)


# --------------------------------------------------------------------------
# Hybrid KEM: secure as long as EITHER component remains unbroken
# --------------------------------------------------------------------------

class HybridKEM(KEM):
    """
    Combines one classical and one post-quantum KEM.

    shared_secret = HKDF( ss_classical || ss_pq ,
                          info = label || ct_classical || ct_pq || pk_classical )

    Binding the ciphertexts and public key into the KDF prevents an attacker
    from mixing components across sessions.
    """
    family, quantum_safe = "hybrid", True

    def __init__(self, classical: KEM, pq: KEM):
        self.classical, self.pq = classical, pq
        self.name = f"{classical.name}+{pq.name}"
        self._label = b"PQCF-Hybrid-v1|" + self.name.encode()

    def keygen(self):
        pk_c, sk_c = self.classical.keygen()
        pk_p, sk_p = self.pq.keygen()
        # classical public key is kept with the secret key so decaps can bind it
        return _pack(pk_c, pk_p), _pack(sk_c, sk_p, pk_c)

    def _combine(self, ss_c, ss_p, ct_c, ct_p, pk_c):
        return _hkdf(ss_c + ss_p, _pack(self._label, ct_c, ct_p, pk_c))

    def encaps(self, public_key):
        pk_c, pk_p = _unpack(public_key)
        ct_c, ss_c = self.classical.encaps(pk_c)
        ct_p, ss_p = self.pq.encaps(pk_p)
        return _pack(ct_c, ct_p), self._combine(ss_c, ss_p, ct_c, ct_p, pk_c)

    def decaps(self, secret_key, ciphertext):
        sk_c, sk_p, pk_c = _unpack(secret_key)
        ct_c, ct_p = _unpack(ciphertext)
        ss_c = self.classical.decaps(sk_c, ct_c)
        ss_p = self.pq.decaps(sk_p, ct_p)
        return self._combine(ss_c, ss_p, ct_c, ct_p, pk_c)
